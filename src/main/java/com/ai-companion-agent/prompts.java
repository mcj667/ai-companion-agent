    /**
     * RAG 检索问答的提示词模板，{@code {question_answer_context}} 是 Spring AI 的固定占位符，
     * 会由 {@code QuestionAnswerAdvisor} 替换成"检索到的几段资料"。
     *
     * <p><b>为什么要自己写一个，不用默认的：</b>默认模板长这样——
     * <pre>
     * Context information is below, surrounded by ---------------------
     * ...
     * Given the context and provided history information and not prior knowledge,
     * reply to the user comment. If the answer is not in the context, inform
     * the user that you can't answer the question.
     * </pre>
     * 问题出在它只丢给模型一堆正文，<b>不说这堆东西是什么</b>。而检索默认只取最相似的 4 段
     * （知识库一共 15 段），所以用户一问"你知道《某文档》吗"，模型手上只有 4 段，
     * 却不知道该说"我只有几段"，只能回一句"我没有这份文档"——听起来像功能坏了，
     * 其实它在如实回答。
     *
     * <p>所以这里把话说清楚：这是"找到的相关内容"、不是全文，有就答、没有就说没有。
     */
